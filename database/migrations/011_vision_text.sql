CREATE TABLE IF NOT EXISTS vision_texts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 content TEXT NOT NULL,
 font VARCHAR(20) NOT NULL DEFAULT 'hand',
 font_size INT NOT NULL DEFAULT 28,
 pos_x INT NOT NULL DEFAULT 30,
 pos_y INT NOT NULL DEFAULT 30,
 width INT NOT NULL DEFAULT 260,
 z_index INT NOT NULL DEFAULT 100,
 CONSTRAINT fk_vision_text_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
